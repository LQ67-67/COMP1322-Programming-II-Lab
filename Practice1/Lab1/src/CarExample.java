// Define a Car class
class Car {
    // Instance variable to store the car's brand
    String brand;
}
// Main class
public class CarExample {
    // main method
    public static void main(String[] args) {

        // Create a Car object
        Car myCar = new Car();

        // Assign a value to the object's brand field
        myCar.brand = "Honda";

        // Print the car brand
        System.out.println("Car brand: " + myCar.brand);
    }
}
